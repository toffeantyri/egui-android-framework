//! Результат обработки Back компонентом.
//!
//! Возвращается из [`ComponentNode::handle_back()`] — единой точки
//! обработки Back для рисованной и платформенной кнопки.

/// Результат обработки Back компонентом.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BackAction {
    /// Компонент полностью обработал Back (закрыл диалог, переключил цвет).
    /// Стек не трогать.
    Handled,

    /// Компонент выполнил свою логику и просит pop текущего экрана.
    Pop,

    /// Компонент просит завершить приложение.
    Finish,

    /// Компонент не обрабатывает Back — передать родительскому стеку.
    Propagate,
}
